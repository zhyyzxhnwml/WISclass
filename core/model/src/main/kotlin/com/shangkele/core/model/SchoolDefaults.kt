     * `ensureDefaultTimeSlots` 只在表为空时写入，如果库里存的恰好还是这组占位值
     * （说明用户从没校准过），就说明它是我早期写错的，直接换成 [TIME_SLOTS]。
     * 用户只要动过任何一个数字就不会匹配上，绝不会覆盖他的校准结果。
