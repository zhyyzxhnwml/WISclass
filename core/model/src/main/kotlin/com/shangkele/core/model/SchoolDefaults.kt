        TimeSlot(9, 19 * 60, 19 * 60 + 45),
        TimeSlot(10, 19 * 60 + 55, 20 * 60 + 40),
        TimeSlot(11, 20 * 60 + 50, 21 * 60 + 35),
        TimeSlot(12, 21 * 60 + 45, 22 * 60 + 30),
    )

    /** 默认作息：上午 08:30 开始。每节 45 分钟，课间 10 分钟，午休后 14:00 继续。 */
    val TIME_SLOTS: List<TimeSlot> = listOf(
