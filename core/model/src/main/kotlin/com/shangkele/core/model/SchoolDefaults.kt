package com.shangkele.core.model

/**
 * 默认作息表。
 *
 * ⚠️ 各节次起止时间是**全项目最容易错、错了影响面最大**的硬编码点：
 * 一旦不对，课表显示、上课自动静音、「该出发了」全部跟着错。
 * 所以这里给的只是**一份保守的默认值**，App 内必须提供校准入口
 * （设置 → 作息表），用户随时能改。
 *
 * 当前默认值按本校「上午 08:30 开始」修正（W3 用户实测反馈）。
 */
