        TimeSlot(12, 21 * 60 + 45, 22 * 60 + 30),
    )

    val WEEKDAY_LABELS = listOf("周一", "周二", "周三", "周四", "周五", "周六", "周日")

    /**
     * 校历默认开学日期：**2026-08-29**（周六，epochDay = 20694）。
     *
     * 注意这是**开学那一天本身，不是那一周的周一**。周次从这一天开始
     * 每 7 天推一格（第 1 周 = 08-29 ~ 09-04），见 [WeekCalculator]。
     *
     * 它仍然只是「用户还没设过」时的占位值。各校开学日不同，真实值必须来自
     * 课表页面显示的周次推算，或用户在「设置 → 校历设置」里手选。
     */
    const val DEFAULT_START_DATE_EPOCH_DAY: Long = 20694L

    /**
     * 早期写死的**占位**校历：2026-08-24（epochDay = 20689）。
     *
     * 这个值从来不是任何学校的开学日，是我在还没有校历来源时随手填的。
     * 演示数据播种和早期版本都用它，所以已经装过的机器库里很可能还是它。
     *
     * 留住它只为一件事：**自愈**。库里恰好等于它、且用户从没亲自设过，
     * 就说明这值不是用户的数据 —— 换成 [DEFAULT_START_DATE_EPOCH_DAY]。
     * 用户只要设过一次，值就匹配不上，绝不会被覆盖。
     */
    const val LEGACY_PLACEHOLDER_START_DATE_EPOCH_DAY: Long = 20689L

    /**
     * 更早的一版错误占位值（2026-09-07）。
